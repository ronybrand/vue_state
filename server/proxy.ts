import { isIP } from 'node:net';
import { UUID_REGEX } from '../src/lib/uuid.js';

// Full catch-all BFF proxy to the Java backend: every /api/* call the browser
// makes is same-origin against this deployment, which forwards it to
// BACKEND_API_URL server-side. The browser therefore never needs CORS on the
// backend, nor a CSP connect-src naming the backend's origin.
//
// Deliberately BACKEND_API_URL, not a VITE_ var: Vite inlines VITE_* into the
// client bundle, which would let httpClient.ts (browser) read the backend URL
// and call it directly, bypassing this proxy.
const REQUEST_ID_HEADER = 'X-Request-Id';
const CLIENT_IP_HEADER = 'X-Client-IP';
const PROXY_SECRET_HEADER = 'X-Proxy-Secret';

// Keeps the normal CRUD requests below httpClient's 15s timeout. The AI agent
// has its own longer timeout because a tool-calling answer can take longer.
export const BACKEND_TIMEOUT_MS = 10_000;
export const AI_AGENT_TIMEOUT_MS = 55_000;

// The app's real payloads (a state, a login) are tens of bytes. Capping the
// body well below the platform limit stops a large upload from being
// buffered in memory here and then forwarded to the backend.
export const MAX_BODY_BYTES = 16 * 1024;

// Only what the app actually calls (see src/services/*). This is a public
// pass-through, so anything not listed - actuator endpoints beyond /info,
// swagger, heapdump, etc. - is unreachable through it even if the backend
// would answer. The regex also rejects any '.'/'..' segment, so a `..%2f`
// can't climb out of BACKEND_API_URL's own path prefix.
const ALLOWED_PATH = /^(estado\/?|estado\/paginado|estado\/\d+|auth\/login|actuator\/info|ask)$/;

// The backend speaks JSON only. Passing through any other Content-Type would
// let it (or anything reflected by it) serve HTML/script from this app's own
// origin - where the app's CSP doesn't apply to /api responses.
const JSON_CONTENT_TYPE = /^application\/([\w.-]+\+)?json\s*(;|$)/i;

// API responses are data, never documents: forbid loading or running anything
// from them, even if a non-JSON body somehow got through.
const API_CSP = "default-src 'none'; frame-ancestors 'none'; sandbox";

function jsonResponse(message: string, status: number): Response {
  return Response.json({ message }, { status });
}

// Reads the body as text, giving up as soon as it exceeds MAX_BODY_BYTES -
// checked on the stream, not just Content-Length, since a chunked request
// carries no length up front. Returns null when over the limit.
async function readBodyCapped(request: Request): Promise<string | null> {
  if (Number(request.headers.get('content-length')) > MAX_BODY_BYTES) {
    return null;
  }
  const reader = request.body?.getReader();
  if (!reader) {
    return '';
  }
  const chunks: Uint8Array[] = [];
  let total = 0;
  for (;;) {
    const { done, value } = await reader.read();
    if (done) {
      break;
    }
    total += value.byteLength;
    if (total > MAX_BODY_BYTES) {
      await reader.cancel();
      return null;
    }
    chunks.push(value);
  }
  return Buffer.concat(chunks).toString('utf8');
}

export async function proxy(request: Request): Promise<Response> {
  // Read per-request, not module-level: a module-level constant is evaluated
  // once at import time, before tests (or any per-request env override) can
  // set BACKEND_API_URL.
  const backendBaseUrl =
    process.env.BACKEND_API_URL ||
    (process.env.NODE_ENV === 'production' ? undefined : 'http://localhost:8080');
  // No silent localhost fallback in production: a missing env var there is a
  // deploy misconfiguration, and a generic 502 "unreachable" would hide it.
  if (!backendBaseUrl) {
    return jsonResponse('BACKEND_API_URL is not configured', 500);
  }

  const url = new URL(request.url);
  const path = url.pathname.replace(/^\/api\/?/, '');
  if (!ALLOWED_PATH.test(path)) {
    return jsonResponse('Not found', 404);
  }
  const backendUrl = `${backendBaseUrl}/${path}${url.search}`;
  const timeoutMs = path === 'ask' ? AI_AGENT_TIMEOUT_MS : BACKEND_TIMEOUT_MS;

  const headers: Record<string, string> = {};
  const authorization = request.headers.get('authorization');
  if (authorization) {
    headers.Authorization = authorization;
  }
  const contentType = request.headers.get('content-type');
  if (contentType) {
    headers['Content-Type'] = contentType;
  }

  // Correlation id generated by httpClient once per user action - it has to
  // reach the backend for its logs to line up with what the client shows.
  // Only a UUID is forwarded: the value lands in the backend's logs, so an
  // arbitrary string (log injection, markup) is dropped, not passed along.
  const requestId = request.headers.get(REQUEST_ID_HEADER);
  if (requestId && UUID_REGEX.test(requestId)) {
    headers[REQUEST_ID_HEADER] = requestId;
  }

  // The backend rate-limits per IP, but everything it sees from here comes
  // from Vercel's own egress IPs - so without this, every visitor shares one
  // bucket. x-vercel-forwarded-for is set by Vercel's edge and can't be
  // supplied by the client. It is sent with a shared secret because the
  // backend must not trust a plain X-Client-IP header from anyone who can
  // reach it directly; both are built here from scratch, never copied from
  // the incoming request, so a browser can't inject either.
  const proxySecret = process.env.BACKEND_PROXY_SECRET;
  const clientIp = request.headers.get('x-vercel-forwarded-for')?.trim();
  if (proxySecret && clientIp && isIP(clientIp)) {
    headers[CLIENT_IP_HEADER] = clientIp;
    headers[PROXY_SECRET_HEADER] = proxySecret;
  }

  const hasBody = !['GET', 'HEAD', 'DELETE'].includes(request.method);
  const requestBody = hasBody ? await readBodyCapped(request) : undefined;
  if (requestBody === null) {
    return jsonResponse('Request body too large', 413);
  }

  try {
    const backendResponse = await fetch(backendUrl, {
      method: request.method,
      headers,
      body: requestBody,
      signal: AbortSignal.timeout(timeoutMs),
    });
    const body = await backendResponse.text();

    const responseType = backendResponse.headers.get('Content-Type');
    if (body && !(responseType && JSON_CONTENT_TYPE.test(responseType))) {
      return jsonResponse('Unexpected backend response', 502);
    }

    const responseHeaders: Record<string, string> = {
      'Content-Type': responseType ?? 'application/json',
      'Content-Security-Policy': API_CSP,
    };
    const responseRequestId = backendResponse.headers.get(REQUEST_ID_HEADER);
    if (responseRequestId && UUID_REGEX.test(responseRequestId)) {
      responseHeaders[REQUEST_ID_HEADER] = responseRequestId;
    }

    return new Response(body || null, {
      status: backendResponse.status,
      headers: responseHeaders,
    });
  } catch (error) {
    if (error instanceof DOMException && error.name === 'TimeoutError') {
      return jsonResponse('Backend timed out', 504);
    }
    return jsonResponse('Failed to reach backend', 502);
  }
}
